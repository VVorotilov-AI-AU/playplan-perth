import type {
  Activity,
  AgeBand,
  Evidence,
  Playground,
  TriState,
} from '../types';
import { PlaygroundSchema } from '../types';

type FacilityInput = Partial<Playground['facilities']>;

const unknownFacilities: Playground['facilities'] = {
  bbq: 'unknown',
  shelter: 'unknown',
  toilets: 'unknown',
  seating: 'unknown',
  fenced: 'unknown',
  accessibleEquipment: 'unknown',
  openLawn: 'unknown',
  shade: 'unknown',
};

interface ParkInput {
  id: string;
  name: string;
  suburb: string;
  council: string;
  address: string;
  lat: number;
  lng: number;
  ages: AgeBand[];
  activities: Activity[];
  facilities: FacilityInput;
  features: string[];
  cautions?: string[];
  sourceUrl: string;
  sourceTitle: string;
  confidence?: Evidence['confidence'];
  status?: Playground['status'];
  bookingUrl?: string;
}

function park(input: ParkInput): Playground {
  const evidence: Evidence = {
    fields: ['ageBands', 'activities', 'facilities', 'status'],
    sourceUrl: input.sourceUrl,
    sourceTitle: input.sourceTitle,
    verifiedAt: '2026-08-25',
    confidence: input.confidence ?? 'high',
  };

  return PlaygroundSchema.parse({
    id: input.id,
    name: input.name,
    suburb: input.suburb,
    council: input.council,
    address: input.address,
    coordinates: { lat: input.lat, lng: input.lng },
    ageBands: input.ages,
    activities: input.activities,
    facilities: { ...unknownFacilities, ...input.facilities },
    standoutFeatures: input.features,
    cautions: input.cautions ?? [],
    bookingUrl: input.bookingUrl,
    evidence: [evidence],
    status: input.status ?? 'open',
    googleMapsUrl: `https://www.google.com/maps/search/?api=1&query=${input.lat},${input.lng}`,
  });
}

